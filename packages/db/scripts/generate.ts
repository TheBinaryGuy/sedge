import { readMigrationFiles } from 'drizzle-orm/migrator';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/*
 * `bun run db:generate -- --name <what>`: runs drizzle-kit, then embeds the result.
 *
 * The shipped binary has no migrations folder next to it, so `db:generate` bakes every migration
 * drizzle-kit wrote into a module the daemon imports. Run after each `drizzle-kit generate`; never
 * edit the output by hand.
 */
const root = dirname(dirname(fileURLToPath(import.meta.url)));

const kit = Bun.spawnSync(['bun', '--bun', 'drizzle-kit', 'generate', ...process.argv.slice(2)], {
    cwd: root,
    stdio: ['inherit', 'inherit', 'inherit'],
});
if (kit.exitCode !== 0) process.exit(kit.exitCode ?? 1);

const migrations = readMigrationFiles({ migrationsFolder: join(root, 'drizzle') });

await Bun.write(
    join(root, 'src/migrations.gen.ts'),
    `// Generated by scripts/generate.ts from ./drizzle. Do not edit.
import type { MigrationMeta } from 'drizzle-orm/migrator';

export const migrations: Array<MigrationMeta> = ${JSON.stringify(migrations, null, 4)};
`,
);
console.log(`Embedded ${migrations.length} migration(s).`);
